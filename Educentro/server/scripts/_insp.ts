import { generarSemillaDemo } from '../src/dev/semilla-demo.js';
const d = generarSemillaDemo();
for (const [k, v] of Object.entries(d)) console.log(k, v.length, JSON.stringify(v[0] ?? null).slice(0, 400));
const dup = (col: string, f: (r: Record<string, any>) => string) => { const m = new Map<string, number>(); for (const r of d[col] ?? []) { const x = f(r); m.set(x, (m.get(x) ?? 0) + 1); } return [...m].filter(([, n]) => n > 1); };
console.log('dup mat', dup('matriculas', (r) => `${r.centroId}|${r.estudianteId}|${r.anioId}`));
for (const c of ['estudiantes', 'docentes', 'tutores']) console.log('dup ced', c, dup(c, (r) => `${r.centroId}|${String(r.documento ?? r.cedula ?? '').replace(/\D/g, '')}`).slice(0, 5));
